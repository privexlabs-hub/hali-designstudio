// Generates src/components/ds/icon-registry.ts: every Lucide icon name referenced anywhere in src/
// (as a quoted kebab-case string or an `icon-<name>` class) is imported by name, so the bundle only
// carries icons that are used. Run automatically before dev/build/typecheck.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const lucide = require('lucide-react');
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'src/components/ds/icon-registry.ts');
const pascal = (n) => n.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');

const names = new Set();
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(tsx?|css)$/.test(e.name) && p !== out) {
      const src = fs.readFileSync(p, 'utf8');
      for (const m of src.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) names.add(m[1]);
      for (const m of src.matchAll(/icon-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) names.add(m[1]);
    }
  }
};
walk(path.join(root, 'src'));

const found = [...names].filter((n) => {
  const c = lucide[pascal(n)];
  return c && (typeof c === 'object' || typeof c === 'function') && pascal(n) !== 'Icon' && pascal(n) !== 'Icons';
}).sort();

const body = `// GENERATED by scripts/gen-icons.mjs — do not edit.\nimport type { LucideIcon } from 'lucide-react';\nimport {\n${found.map((n) => `  ${pascal(n)},`).join('\n')}\n} from 'lucide-react';\n\nexport const ICONS: Record<string, LucideIcon> = {\n${found.map((n) => `  '${n}': ${pascal(n)},`).join('\n')}\n};\n`;
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (prev !== body) fs.writeFileSync(out, body);
console.log(`icon-registry: ${found.length} icons`);
